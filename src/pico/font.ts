const ASCII_123_126 = ['32623', '22222', '62326', '03600'];

export const GLYPHS: Record<number, number[]> = {};
for (let i = 0; i < ASCII_32_96.length; i++) GLYPHS[32 + i] = [...ASCII_32_96[i]].map(Number);
for (let i = 0; i < 4; i++) GLYPHS[123 + i] = [...ASCII_123_126[i]].map(Number);
for (let c = 97; c <= 122; c++) GLYPHS[c] = GLYPHS[c - 32];

