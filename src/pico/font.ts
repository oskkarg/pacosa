/** Returns [rows, width, isWide] for a character or null */
export function glyphFor(ch: string): [number[], number, boolean] | null {
  if (ch.length === 1) {
    const code = ch.charCodeAt(0);
    const g = GLYPHS[code];
    if (g) return [g, 3, false];
  }
  const k = ch.replace(/\uFE0F/g, '');
  const w = WIDE[k];
  if (w) return [w, 7, true];
  return null;
}

